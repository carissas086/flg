                        <p class="medium italics bold">Arcrylic Painting</p>
                        <p>The sermon series this Christmas season is entitled &ldquo;Keep Watch&rdquo; inspired by Matthew 24-25 and reading through these passages, the part about the day and hour of Jesus&apos; return being unknown stood out to me. An image of an hourglass came to my mind. The sand in the hour glass is falling to indicate that Jesus is indeed coming back, but there is no clear indication when the time will reach the end. For all we know, the hourglass could just flip around and the sand would still continue falling.</p>
                        <p>We as His followers must be ready. We cannot slip into a comfortable state, just living life without the knowledge of our Lord and pushing obedience to Him to the side. We are to &ldquo;keep watch&rdquo; by living a life that is holy and pleasing to Him alone. What does that life look like?</p>
