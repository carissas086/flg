                        <h3 class="head-font christmas24-header">Anticipation</h3>
                        <p class="medium italics bold">Arcrylic Painting</p>
                        <p>This oil painting was started on November 11th, 2024, after my family participated in a Remembrance Day Ceremony. Advent candles help us remember that God keeps His promises.</p>
                        <p>The first candle (purple) is the Prophecy Candle or Candle of Hope: our hope comes from God. <span class="italics">(Romans 15:12-13)</span></P>
                        <p>The second candle (purple) is the Bethlehem Candle or the Candle of Preparation: &ldquo;get ready&rdquo; to welcome God. <span class="italics">(Luke 3:4-6)</span></P>
                        <p>The third candle (pink) is the Shepherd Candle or the Candle of Joy: the angels sang a message of joy. <span class="italics">(Luke 2:7-15)</span></P>
                        <p>The fourth candle (purple) is the Angel Candle or the Candle of Love: the angels announced the good news of a Savior sent by God who loves us. <span class="italics">(John 3:16-17)</span></P>
                        <p>The fifth candle (white) is the &ldquo;Christ Candle&rdquo; representing Jesus as the spotless Lamb of God who was sent towash away our sins. <span class="italics">(John 1:29)</span></P>
                        <p>The backlit cross in the window frame against a starry night reminds us that Jesus will return as promised.</p>
